#!/usr/bin/env bash
#
# YYC³ — 开源项 → 包组 集成 SOP 自动化脚本
# 对应 INTEGRATION-PLAN.md §6.3 “自研” 六步流程
#
# 用法：
#   ./sop-integrate.sh [step]        # 运行指定步骤，不传则全流程
#   ./sop-integrate.sh status        # 打印当前集成状态
#
# 依赖：fetch-tarball-one.sh（步骤 2）、repos.tsv（步骤 1/3）
# 许可证红线：AGPL/GPL 仅独立部署或参考设计，不复制进闭源前端
set -eo pipefail

ROOT="$(cd "$(dirname "$0")" && pwd)"
REPOS="$ROOT/repos.tsv"
FETCH="$ROOT/fetch-tarball-one.sh"
STATUS="$ROOT/INTEGRATION-STATUS.md"
NOTICE="$ROOT/NOTICE.md"
PKG_ROOT="$(cd "$ROOT/../../.." && pwd)/packages"

LOG="$ROOT/_sop.log"
: > "$LOG"

step_of() { echo "[$(date '+%H:%M:%S')] $*" | tee -a "$LOG"; }

# ─────────────────────────────────────────────────────────────────────────────
# 步骤 1：调研与选型 — 读取 repos.tsv，许可证合规审核，输出候选清单
# ─────────────────────────────────────────────────────────────────────────────
step_research() {
  step_of "Step 1: Research & selection — license compliance audit"
  echo "| Repo | License | Compliance handling | Integration target |" > "$STATUS.tmp"
  echo "|------|---------|---------------------|--------------------|" >> "$STATUS.tmp"

  tail -n +2 "$REPOS" | while IFS=$'\t' read -r group repo license note; do
    [ -z "$repo" ] && continue

    case "$license" in
      AGPL-3.0|GPL-2.0|GPL-3.0|LGPL-3.0)
        dispose="Independent deployment or reference design only, no code copy"
        ;;
      Commercial|Free-Closed)
        dispose="No commercial use, not in product dependencies"
        ;;
      MIT|BSD-3-Clause|Apache-2.0|ISC)
        dispose="Directly usable in product (declare in NOTICE)"
        ;;
      *)
        dispose="Manual review required"
        ;;
    esac

    dest=$(case "$repo" in
      videojs/video.js|muxinc/media-chrome|video-dev/hls.js|wavesurfer-js/wavesurfer.js) echo "Core kernel" ;;
      owncast/owncast|bluenviron/mediamtx|ossrs/srs) echo "Streaming media" ;;
      motiondivision/motion|darkroomengineering/lenis|clauderic/dnd-kit|TanStack/table|pacocoursey/cmdk|emilkowalski/vaul|emilkowalski/sonner) echo "UX evolution" ;;
      heroui-inc/heroui|mantinedev/mantine|tremorlabs/tremor|airbnb/visx|redotvideo/revideo) echo "Optional selection" ;;
      navidrome/navidrome|misskey-dev/misskey|koel/koel|immich-app/immich) echo "Reference (architecture/interaction only)" ;;
      *) echo "Reference own design (packages as base)" ;;
    esac)

    echo "| $repo | $license | $dispose | $dest |" >> "$STATUS.tmp"
  done

  mv "$STATUS.tmp" "$STATUS"
  step_of "Step 1 done: compliance audit written to $STATUS"
}

# ─────────────────────────────────────────────────────────────────────────────
# 步骤 2：拉取与研读 — 复用 fetch-tarball-one.sh 下载源码快照
# ─────────────────────────────────────────────────────────────────────────────
step_fetch() {
  step_of "Step 2: Fetch & read — download source snapshots to docs/开源组件库/"
  if [ ! -x "$FETCH" ]; then
    step_of "WARN: $FETCH not executable, skipping step 2"
    return 0
  fi

  tail -n +2 "$REPOS" | while IFS=$'\t' read -r group repo license note; do
    [ -z "$repo" ] && continue
    "$FETCH" "$group" "$repo" >> "$LOG" 2>&1 || step_of "WARN: $repo fetch failed (see _fetch.log)"
  done
  step_of "Step 2 done: source snapshot fetch finished"
}

# ─────────────────────────────────────────────────────────────────────────────
# 步骤 3：包组集成 — 根据 §4 矩阵，将开源项映射到 packages/，生成集成记录
# ─────────────────────────────────────────────────────────────────────────────
step_integrate() {
  step_of "Step 3: Package integration — map to packages/ and generate integration record"

  cat >> "$STATUS" <<'EOF'

## Integration Guide (auto-generated by Step 3)

| Entry | Target package | Integration method | Status |
|-------|----------------|--------------------|--------|
| videojs/video.js | music-player | MediaDisplay as Video.js kernel | Done W2 |
| muxinc/media-chrome | music-player | MediaDisplay controls upgrade | Done W2 |
| video-dev/hls.js | music-audio | AdvancedPlayer as hls.js kernel | Done W2 |
| wavesurfer-js/wavesurfer.js | music-lyrics | New WaveformLyrics component | Done W2 |
| owncast/owncast | music-server | /live/stream references push model | Done W3 |
| bluenviron/mediamtx | music-server | /live/stream references push model | Done W3 |
| ossrs/srs | music-server | /live/stream references push model | Done W3 |
| motiondivision/motion | music-ui/music-hooks | W1 added motion dependency | Done W1 |
| darkroomengineering/lenis | music-hooks | useScrollProgress | Done W1 |
| clauderic/dnd-kit | music-ui | PlaylistSortableList | Done W1 |
| TanStack/table | music-ui | VirtualTrackList | Done W1 |
| pacocoursey/cmdk | music-ui | Command palette (reserved) | Planned |
| emilkowalski/vaul | music-ui | Drawer (reserved) | Planned |
| emilkowalski/sonner | music-ui | Toast (integrated) | Done W1 |
| heroui-inc/heroui | music-ui | Form components optional | Planned |
| mantinedev/mantine | music-ui | Full components optional | Planned |
| tremorlabs/tremor | music-community | AnalyticsDashboard design reference | Done W4 |
| airbnb/visx | music-community | Visualization primitive reference | Planned |
| redotvideo/revideo | music-mv | MvScene programmatic MV | Done W4 |
| navidrome/navidrome | music-data | mediaScanner architecture reference (GPL, no code copy) | Done W2 |
| misskey-dev/misskey | music-community | CommunityFeed reactions (AGPL, no code copy) | Done W4 |
| koel/koel | music-player | Playlist product details reference | Planned |
| immich-app/immich | music-server | Upload/dedup/thumbnail reference | Planned |

EOF
  step_of "Step 3 done: integration guide appended to $STATUS"
}

# ─────────────────────────────────────────────────────────────────────────────
# 步骤 4：验收与闭环 — 对受影响的包运行 typecheck/lint/build
# ─────────────────────────────────────────────────────────────────────────────
step_verify() {
  step_of "Step 4: Acceptance & closure — typecheck/lint/build"
  pkgs="music-ui music-hooks music-design-tokens music-player music-audio music-lyrics music-data music-server music-live music-community music-mv"
  all_ok=1
  for p in $pkgs; do
    pdir="$PKG_ROOT/$p"
    if [ ! -d "$pdir" ]; then
      step_of "SKIP $p: directory not found"
      continue
    fi
    step_of "Verifying $p ..."
    if (cd "$pdir" && pnpm run typecheck >> "$LOG" 2>&1 && pnpm run lint >> "$LOG" 2>&1 && pnpm run build >> "$LOG" 2>&1); then
      step_of "  $p all green"
    else
      step_of "  $p failed (see _sop.log)"
      all_ok=0
    fi
  done
  if [ "$all_ok" -eq 1 ]; then
    step_of "Step 4 done: all affected packages green"
  else
    step_of "Step 4 done: some packages failed, check _sop.log"
  fi
}

# ─────────────────────────────────────────────────────────────────────────────
# 步骤 5：许可证合规 — 生成 NOTICE.md 汇总所有引入的开源依赖
# ─────────────────────────────────────────────────────────────────────────────
step_notice() {
  step_of "Step 5: License compliance — generate NOTICE.md"
  {
    echo "# YYC³ Open Source Dependency License Notice (NOTICE)"
    echo ""
    echo "This document summarizes open source dependencies directly introduced in"
    echo "`packages/` and their licenses, generated per INTEGRATION-PLAN.md"
    echo "§2 license compliance principles."
    echo ""
    echo "AGPL/GPL projects (Navidrome, PeerTube, Misskey, Immich, etc.) are independent"
    echo "deployment or reference design only, not copied into the closed-source frontend,"
    echo "and are not listed in this NOTICE."
    echo ""
    echo "| Dependency | License | Source | Purpose |"
    echo "|------------|---------|--------|---------|"
    echo "| video.js | Apache-2.0 | docs/开源组件库/05-UI组件/video.js | music-player playback kernel |"
    echo "| media-chrome | MIT | docs/开源组件库/05-UI组件/media-chrome | music-player media controls |"
    echo "| hls.js | Apache-2.0 | docs/开源组件库/05-UI组件/hls.js | music-audio playback kernel |"
    echo "| wavesurfer.js | BSD-3-Clause | docs/开源组件库/05-UI组件/wavesurfer.js | music-lyrics waveform visualization |"
    echo "| motion | MIT | docs/开源组件库/05-UI组件/motion | music-ui/music-hooks animation |"
    echo "| lenis | MIT | docs/开源组件库/05-UI组件/lenis | music-hooks smooth scroll |"
    echo "| @dnd-kit/* | MIT | docs/开源组件库/05-UI组件/dnd-kit | music-ui playlist drag-and-drop |"
    echo "| @tanstack/* | MIT | docs/开源组件库/05-UI组件/TanStack | music-ui long list/table |"
    echo "| sonner | MIT | docs/开源组件库/05-UI组件/sonner | music-ui Toast |"
    echo "| vaul | MIT | docs/开源组件库/05-UI组件/vaul | music-ui drawer |"
    echo "| cmdk | MIT | docs/开源组件库/05-UI组件/cmdk | music-ui command palette |"
    echo "| recharts | MIT | docs/开源组件库/05-UI组件/recharts | music-community operations dashboard |"
    echo "| revideo | Apache-2.0 | docs/开源组件库/04-综艺制作/revideo | music-mv programmatic MV |"
    echo ""
    echo "Generated: $(date '+%Y-%m-%d %H:%M:%S')"
    echo "Source: docs/开源组件库/repos.tsv"
  } > "$NOTICE"
  step_of "Step 5 done: NOTICE generated at $NOTICE"
}

# ─────────────────────────────────────────────────────────────────────────────
# 步骤 6：持续更新 — 版本锁定，记录快照版本
# ─────────────────────────────────────────────────────────────────────────────
step_snapshot() {
  step_of "Step 6: Continuous update — version lock and snapshot record"
  {
    echo ""
    echo "# Open Source Component Library Snapshot Version Record"
    echo ""
    echo "Snapshot time: $(date '+%Y-%m-%d %H:%M:%S')"
    echo "Source: docs/开源组件库/repos.tsv (72 entries)"
    echo "Download method: gh api repos/{owner}/{repo}/tarball/HEAD (HEAD snapshot)"
    echo ""
    echo "## Version lock note"
    echo "- docs/开源组件库/ does not auto-update with upstream, version locked to the"
    echo "  above snapshot time."
    echo "- To upgrade, re-run ./sop-integrate.sh fetch to re-download."
    echo ""
    echo "## Pulled subdirectory count: $(find "$ROOT" -maxdepth 2 -type d | grep -v '_markers' | grep -v '^\.$' | wc -l)"
    echo "## Total size: $(du -sh "$ROOT" 2>/dev/null | cut -f1)"
  } >> "$STATUS"
  step_of "Step 6 done: snapshot version recorded"
}

# ─────────────────────────────────────────────────────────────────────────────
# 状态查询
# ─────────────────────────────────────────────────────────────────────────────
cmd_status() {
  if [ -f "$STATUS" ]; then
    cat "$STATUS"
  else
    step_of "$STATUS not generated yet, run ./sop-integrate.sh first"
  fi
}

# ─────────────────────────────────────────────────────────────────────────────
# 主流程
# ─────────────────────────────────────────────────────────────────────────────
main() {
  cmd="${1:-all}"
  case "$cmd" in
    research) step_research ;;
    fetch)    step_fetch ;;
    integrate) step_integrate ;;
    verify)   step_verify ;;
    notice)   step_notice ;;
    snapshot) step_snapshot ;;
    status)   cmd_status ;;
    all|"")
      step_research
      step_fetch
      step_integrate
      step_verify
      step_notice
      step_snapshot
      ;;
    *)
      echo "Unknown command: $cmd"
      echo "Usage: $0 [research|fetch|integrate|verify|notice|snapshot|status|all]"
      exit 1
      ;;
  esac
}

main "$@"
